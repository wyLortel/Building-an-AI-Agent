export function calculate(expression: string): number {
  // calculate라는 함수를 만든다.
  // expression에는 "2 + 3 * 4" 같은 계산식 문자열이 들어온다.
  // 마지막에는 계산 결과(number)를 돌려준다.

  const tokens = expression.match(/\d+\.?\d*|[+\-*/()]/g);
  // 계산식을 작은 조각들(token)로 잘라낸다.
  //
  // 예:
  // "2 + 3 * 4"
  //      ↓
  // ["2", "+", "3", "*", "4"]
  //
  // "10.5 * (2 + 3)"
  //      ↓
  // ["10.5", "*", "(", "2", "+", "3", ")"]
  //
  // 정규식 부분:
  // \d+      → 숫자가 1개 이상
  // \.?      → 소수점이 있을 수도 있고 없을 수도 있음
  // \d*      → 소수점 뒤 숫자가 0개 이상
  // |        → 또는
  // [+\-*/()] → + - * / ( ) 중 하나
  //
  // g        → 하나만 찾지 말고 전부 찾아라

  if (!tokens) throw new Error('빈 수식');
  // 잘라낸 토큰이 아예 없다면
  // 계산할 것이 없다는 뜻.
  //
  // 예:
  // calculate("")
  //
  // → 에러 발생

  let pos = 0;
  // 지금 tokens의 몇 번째 위치를 읽고 있는지 저장한다.
  //
  // 예:
  // tokens = ["2", "+", "3"]
  //
  //           ↑
  // pos = 0
  //
  // 처음에는 첫 번째 토큰부터 읽는다.

  const peek = () => tokens[pos];
  // 현재 위치의 토큰을 "보기만" 한다.
  // 위치(pos)는 움직이지 않는다.
  //
  // 예:
  // tokens = ["2", "+", "3"]
  // pos = 0
  //
  // peek() → "2"
  //
  // 하지만 pos는 여전히 0

  const next = () => tokens[pos++];
  // 현재 토큰을 가져온 뒤,
  // pos를 다음 칸으로 이동한다.
  //
  // 예:
  // tokens = ["2", "+", "3"]
  // pos = 0
  //
  // next() → "2"
  //
  // 그 다음:
  // pos = 1
  //
  //              ↑
  // ["2", "+", "3"]

  function parseExpr(): number {
    // +와 - 계산을 담당하는 함수다.
    //
    // Expr = Expression(표현식)의 줄임말
    //
    // 예:
    // 10 + 3 - 2

    let v = parseTerm();
    // 먼저 숫자 하나를 그냥 읽는 게 아니라
    // 곱셈/나눗셈까지 먼저 계산한다.
    //
    // 왜?
    //
    // 2 + 3 * 4
    //
    // 여기서 3 * 4를 먼저 해야 하기 때문.
    //
    // parseTerm()이 *와 /를 담당한다.

    while (peek() === '+' || peek() === '-') {
      // 다음 토큰이 + 또는 -인 동안 계속 계산한다.
      //
      // 예:
      //
      // 10 + 3 - 2
      //    ↑
      //
      // +니까 while 안으로 들어간다.

      const op = next();
      // 현재 연산자(+ 또는 -)를 가져온다.
      //
      // 예:
      // op = "+"
      //
      // next()를 사용했으므로
      // 위치도 다음으로 이동한다.

      const r = parseTerm();
      // 연산자 오른쪽 숫자를 가져온다.
      //
      // 예:
      // 10 + 3
      //
      //      ↑
      //      r = 3
      //
      // 그런데 그냥 숫자 하나가 아니라
      // 곱하기/나누기까지 계산한 결과를 가져온다.

      v = op === '+' ? v + r : v - r;
      // op가 "+"라면:
      //
      // v + r
      //
      // 아니라면("-"라면):
      //
      // v - r
      //
      // 예:
      //
      // v = 10
      // op = "+"
      // r = 3
      //
      // 결과:
      // v = 13
    }

    return v;
    // +와 - 계산을 모두 끝낸 결과를 반환한다.
  }

  function parseTerm(): number {
    // *와 / 계산을 담당하는 함수다.
    //
    // Term은 곱셈/나눗셈 덩어리라고 생각하면 된다.
    //
    // 예:
    // 3 * 4 / 2

    let v = parseFactor();
    // 가장 작은 계산 단위 하나를 먼저 가져온다.
    //
    // 숫자일 수도 있고:
    // 3
    //
    // 괄호일 수도 있다:
    // (2 + 3)

    while (peek() === '*' || peek() === '/') {
      // 다음 토큰이 * 또는 /라면
      // 계속 곱셈/나눗셈을 한다.

      const op = next();
      // "*" 또는 "/"를 가져온다.
      //
      // 예:
      // op = "*"

      const r = parseFactor();
      // 연산자 오른쪽 값을 가져온다.
      //
      // 예:
      // 3 * 4
      //
      //     ↑
      //     r = 4

      if (op === '/' && r === 0) throw new Error('0으로 나눌 수 없습니다');
      // 나눗셈인데 오른쪽 숫자가 0이면 에러.
      //
      // 예:
      // 10 / 0
      //
      // 수학에서 0으로 나눌 수 없으므로 막는다.

      v = op === '*' ? v * r : v / r;
      // op가 "*"이면 곱하기
      // 아니면 "/"이므로 나누기
      //
      // 예:
      //
      // v = 3
      // op = "*"
      // r = 4
      //
      // v = 12
    }

    return v;
    // 곱셈/나눗셈 결과를 반환한다.
  }

  function parseFactor(): number {
    // 계산에서 가장 작은 단위를 처리한다.
    //
    // Factor가 처리하는 것은 크게 두 가지:
    //
    // ① 숫자
    // ② 괄호
    //
    // 예:
    // 5
    //
    // 또는
    //
    // (2 + 3)

    if (peek() === '(') {
      // 현재 토큰이 "(" 라면
      // 괄호 계산을 시작한다.

      next();
      // "("를 먹고 다음 위치로 이동한다.
      //
      // 예:
      //
      // ( 2 + 3 )
      // ↑
      //
      // next()
      //
      //   ↑
      // ( 2 + 3 )

      const v = parseExpr();
      // 괄호 안쪽을 하나의 새로운 계산식으로 계산한다.
      //
      // 예:
      //
      // (2 + 3)
      //
      // parseExpr()
      //
      // → 5
      //
      // 따라서 v = 5

      if (next() !== ')') throw new Error('괄호가 맞지 않습니다');
      // 괄호 안 계산이 끝났으면
      // 반드시 ")"가 나와야 한다.
      //
      // 예:
      //
      // (2 + 3)
      //       ↑
      //       정상
      //
      // 하지만
      //
      // (2 + 3
      //
      // ")"가 없으므로 에러

      return v;
      // 괄호 안 계산 결과를 반환한다.
      //
      // (2 + 3)
      //    ↓
      //    5
    }

    const t = next();
    // 괄호가 아니라면
    // 현재 토큰을 하나 가져온다.
    //
    // 예:
    //
    // ["10", "+", "3"]
    //   ↑
    //
    // t = "10"

    const n = Number(t);
    // 문자열로 되어 있는 숫자를
    // 실제 number 타입으로 바꾼다.
    //
    // "10"
    //   ↓
    // 10

    if (Number.isNaN(n)) throw new Error(`예상치 못한 토큰: ${t}`);
    // 숫자로 바꿀 수 없다면 이상한 값이 들어온 것.
    //
    // 예:
    //
    // t = "hello"
    //
    // Number("hello")
    // → NaN
    //
    // 그러면 에러를 발생시킨다.

    return n;
    // 정상적인 숫자라면 그 숫자를 반환한다.
  }

  const result = parseExpr();
  // 이제 계산식을 처음부터 실제로 계산한다.
  //
  // 예:
  //
  // "2 + 3 * 4"
  //
  // parseExpr()
  //       ↓
  //      14
  //
  // result = 14

  if (pos !== tokens.length) throw new Error('수식 파싱 실패');
  // 모든 토큰을 제대로 사용했는지 검사한다.
  //
  // 예:
  //
  // tokens가 5개인데
  // pos가 3에서 끝났다면?
  //
  // ["2", "+", "3", "?", "5"]
  //                   ↑
  //
  // 아직 안 읽은 게 남았다는 뜻.
  //
  // 그러면 정상적인 수식이 아니라고 판단한다.

  return result;
  // 최종 계산 결과를 사용자에게 돌려준다.
}
